export const sceneFor = (missionId: string): string[] | undefined =>
  SCENES[missionId];

export const levelSceneFor = (levelId: string): string | undefined =>
  LEVEL_SCENES[levelId];

/** Exposed so a test can keep every mission and level narrated. */
export const missionsWithoutScenes = (): string[] =>
  ALL_MISSIONS.filter((mission) => !SCENES[mission.id]?.length).map(
    (mission) => mission.id,
  );

export const levelsWithoutScenes = (): string[] =>
  LEVELS.filter((level) => !LEVEL_SCENES[level.id]).map((level) => level.id);
