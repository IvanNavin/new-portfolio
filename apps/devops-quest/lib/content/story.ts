/** Тарас, in his own voice, when a mission is done. */
export const heroReaction = (stars: number, hintsUsed: number): string => {
  if (stars === 3)
    return 'Ну ось. Без жодної підказки — значить, я справді зрозумів.';
  if (hintsUsed === 1)
    return 'Одна підказка. Оксана сказала б, що це нормально.';
  return 'Розібрався. Наступного разу буде швидше.';
};

