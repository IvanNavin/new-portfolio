/** What Тарас says when a mission is done, by how much help it took. */
export const praiseFor = (stars: number, hintsUsed: number): string => {
  if (stars === 3)
    return 'Чисто. Без жодної підказки — саме так це й має виглядати.';
  if (hintsUsed === 1)
    return 'Добре. Одна підказка — це нормально, я теж досі гуглю.';
  return 'Готово. Головне, що зрозумів — швидкість прийде сама.';
};

